'use strict';
/**
 * Builds public/index.html from src/ (no dependencies).
 *
 *   node scripts/build.js           write public/index.html, public/sw.js, lib/csp-hashes.json and the vercel.json CSP
 *   node scripts/build.js --check   exit 1 if any of them is out of date (the tests run this)
 *
 * Why a single file? A worksheet can be downloaded as one self-contained .html file, and the app
 * produces that file by re-reading its own page source. So the built page must stay one file.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { buildCsp } = require('../lib/security');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const PUBLIC = path.join(ROOT, 'public');
const OUTPUT = path.join(PUBLIC, 'index.html');
const HASH_FILE = path.join(ROOT, 'lib', 'csp-hashes.json');
const VERCEL_FILE = path.join(ROOT, 'vercel.json');
const SW_TEMPLATE = path.join(SRC, 'sw.template.js');
const SW_OUTPUT = path.join(PUBLIC, 'sw.js');

/** Everything the service worker keeps for offline use. '/' is the built page itself. */
const APP_FILES = [
  '/',
  '/manifest.webmanifest',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon-maskable-512.png',
  '/icons/apple-touch-icon.png',
  '/privacy.html'
];

/** Order matters: scripts share one scope, and later files use what earlier files define. */
const STYLES = [
  'styles/01-base.css',
  'styles/02-shell-and-teacher.css',
  'styles/03-player.css',
  'styles/04-devices.css'
];
const SCRIPTS = [
  'js/core/ui.js',
  'js/core/text.js',
  'js/core/worksheet.js',
  'js/core/grading.js',
  'js/core/speech.js',
  'js/core/deck.js',
  'js/core/local-data.js',
  'js/core/offline.js',
  'js/core/platform.js',
  'js/share/codec.js',
  'js/share/qr.js',
  'js/share/standalone.js',
  'js/player/state.js',
  'js/player/items.js',
  'js/player/markup.js',
  'js/player/practice.js',
  'js/player/deck-panel.js',
  'js/player/player.js',
  'js/player/home.js',
  'js/teacher/upload.js',
  'js/teacher/review.js',
  'js/teacher/share.js',
  'js/teacher/teacher.js',
  'js/main.js'
];

const read = file => fs.readFileSync(path.join(SRC, file), 'utf8').replace(/\s+$/, '') + '\n';

function build() {
  const styles = STYLES.map(read).join('\n');
  const body = SCRIPTS.map(read).join('\n');
  // Everything runs inside one function so nothing leaks into the global scope.
  const script = "(function () {\n'use strict';\n\n" + body + '\n})();';
  const html = read('index.template.html')
    .replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build.js from src/. Edit the files in src/, then run: npm run build -->')
    // Function replacers: the code contains "$" characters that must not be treated as patterns.
    .replace('/*{{STYLES}}*/', () => styles.trimEnd())
    .replace('/*{{SCRIPT}}*/', () => script);
  return html;
}

/**
 * The service worker, with its version and file list filled in. The version changes whenever the page,
 * an icon, the manifest or the worker itself changes, which is what makes browsers install the update.
 */
function buildServiceWorker(indexHtml) {
  const template = fs.readFileSync(SW_TEMPLATE, 'utf8');
  const digest = crypto.createHash('sha256').update(template);
  APP_FILES.forEach(url => digest.update(url + '\0').update(url === '/' ? indexHtml : fs.readFileSync(path.join(PUBLIC, url))));
  const version = digest.digest('hex').slice(0, 12);
  return template
    .replace('{{VERSION}}', () => version)
    .replace('{{APP_FILES}}', () => JSON.stringify(APP_FILES));
}

/** sha256 (base64) of every inline script that runs. JSON data blocks never execute and are skipped. */
function inlineScriptHashes(html) {
  const hashes = [];
  const pattern = /<script([^>]*)>([\s\S]*?)<\/script>/g;
  let match;
  while ((match = pattern.exec(html))) {
    const isRunnable = !/\bsrc=/.test(match[1]) && !/type="application\/json"/.test(match[1]);
    if (isRunnable) hashes.push(crypto.createHash('sha256').update(match[2]).digest('base64'));
  }
  return hashes;
}

/** Hashes for the built index.html plus any other page in public/ that has inline scripts. */
function collectHashes(indexHtml) {
  const others = fs.readdirSync(PUBLIC)
    .filter(name => name.endsWith('.html') && name !== 'index.html')
    .map(name => fs.readFileSync(path.join(PUBLIC, name), 'utf8'));
  return Array.from(new Set([indexHtml].concat(others).flatMap(inlineScriptHashes))).sort();
}

/** What every generated file should contain right now. */
function expectedFiles() {
  const html = build();
  const hashes = collectHashes(html);
  const vercel = JSON.parse(fs.readFileSync(VERCEL_FILE, 'utf8'));
  const csp = vercel.headers[0].headers.find(header => header.key === 'Content-Security-Policy');
  csp.value = buildCsp(hashes);
  return [
    { file: OUTPUT, content: html },
    { file: SW_OUTPUT, content: buildServiceWorker(html) },
    { file: HASH_FILE, content: JSON.stringify({ scripts: hashes }, null, 2) + '\n' },
    { file: VERCEL_FILE, content: JSON.stringify(vercel, null, 2) + '\n' }
  ];
}

function outOfDate() {
  return expectedFiles().filter(({ file, content }) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content);
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const stale = outOfDate().map(({ file }) => path.relative(ROOT, file));
    if (stale.length) {
      console.error('Out of date: ' + stale.join(', ') + '. Run: npm run build');
      process.exit(1);
    }
    console.log('Generated files are up to date.');
  } else {
    expectedFiles().forEach(({ file, content }) => fs.writeFileSync(file, content));
    console.log('Built public/index.html, public/sw.js, lib/csp-hashes.json and the vercel.json CSP.');
  }
}

module.exports = { build, buildServiceWorker, outOfDate, inlineScriptHashes, SCRIPTS, STYLES, SRC, APP_FILES, PUBLIC };
